/**
 * タスクの粒度。どれくらいの重さかを表す。
 *
 * 3つの提案カードは、この粒度を散らして作る。
 * 同じ重さが3つ並ぶと、どれを選んでも同じになり、3つから選ぶ意味が失われるため。
 *
 * 目安は次のとおり。
 * FIVE_MIN … 10分以内
 * TODAY    … 今日中に終わる
 * GROUP    … 一度では終わらず、何回かに分かれる
 *
 * ProposalCard.estimatedMinutes と食い違わないようにする。
 * 3分の案に GROUP が付いていると、選ぶ手がかりにならない。
 *
 * それぞれに label（画面に出す日本語）を持たせている。
 * 表示の文言をコード側にまとめておくと、画面側で条件分岐を書かずに済み、
 * 文言を直すときも1か所で済む。
 *
 * データベースには文字列で保存する（ProposalCard の @Enumerated(EnumType.STRING)）。
 * 指定しない場合は 0, 1, 2 という並び順の数字で保存されるため、
 * 項目の追加や順序の変更によって、保存済みデータの意味がずれる。
 */
public enum Granularity {

	// ===== 値 =====
	// 括弧の中は、下のコンストラクタに渡す label。

	/** 10分以内で終わる。もう動けないと思っている人でも手が出る大きさ */
	FIVE_MIN("5分でできる"),

	/** 今日中に終わり、進んだと目で分かる大きさ */
	TODAY("今日中にできる"),

	/** 一度では終わらない。何回かに分けて進める大きさ */
	GROUP("まとまった時間が要る");

	// ===== フィールド =====

	/**
	 * 画面に出す日本語。
	 *
	 * final なので、いちど入れたら変えられない。
	 * 列挙型の値はアプリ全体で1つずつしか存在しないため、
	 * 書き換えられるとどこから見ても変わってしまう。それを防いでいる。
	 */
	private final String label;

	// ===== コンストラクタ =====

	/**
	 * 上に並べた値から呼ばれる。
	 *
	 * 列挙型のコンストラクタは必ず private 扱いになるため、
	 * private を書いても書かなくても同じ意味になる。
	 * 外から new Granularity(...) と書くことはできない。
	 */
	private Granularity(String label) {
		this.label = label;
	}

	// ===== メソッド =====

	/**
	 * 画面に出す日本語を返す。
	 *
	 * 画面からは ${card.granularity.label} の形で呼ばれる。
	 * Thymeleaf は .label と書かれたとき getLabel() を探しに行くので、
	 * この getter が無いと値を読めない。
	 */
	public String getLabel() {
		return label;
	}
}
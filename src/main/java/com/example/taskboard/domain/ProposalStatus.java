/**
 * 提案1セットの状態。1回のスタートで作られる3案が、いまどうなっているかを表す。
 *
 * 状態が変わるのは ProposalService の中だけで、次の3か所。
 * 1. 3案を作った直後            → OPEN
 * 2. カードが選ばれたとき        → CHOSEN（choose）
 * 3. 「別の案を見る」が押されたとき → RETOPIC（retopic）
 *
 * 【OPEN のまま残るセットがある】
 *
 * 3案を出したあと、選ばずに画面を閉じると OPEN のまま残る。
 * これは消さず、そのままにしておく。
 *
 * 次にスタートを押したときは、新しいセットを作る。
 * 残っている OPEN を探して使い回すことはしない。
 * 時間が経てば状況が変わっていて、そのときの3案は合わなくなるため。
 *
 * 以前は使い回していた。スタート画面を開いた時点で裏に1セット作っておき、
 * 押されたら OPEN のものを出すことで、待ち時間を消していた。
 * だが1回のスタートで AI を2回呼ぶことになり、
 * 無料枠（1日20回）が実質半分になるのでやめた。
 *
 * 使い回さなくなったので、期限の仕組みも要らなくなった。
 * 以前は古い OPEN を期限切れにする設定を持っていたが、
 * 探しに行かないのであれば、古いかどうかを気にする必要がない。
 *
 * 【残しておく理由】
 *
 * OPEN は「出したが選ばれなかった」という記録になる。
 * CHOSEN と合わせて数えれば、押したあと実際に選んだ割合が分かる。
 *
 * RETOPIC は「3案とも合わなかった」という、もっとはっきりした手がかりになる。
 * これが多い時間帯や分野があれば、提案の出し方を見直す材料になる。
 *
 * どれも提案の質を測るためのもので、消してしまうと後から数えられない。
 *
 * データベースには文字列で保存する（ProposalSet の @Enumerated(EnumType.STRING)）。
 * 指定しない場合は 0, 1, 2 という並び順の数字で保存されるため、
 * 項目の追加や順序の変更によって、保存済みデータの意味がずれる。
 */
public enum ProposalStatus {

	// ===== 値 =====

	/** 3案を出して、まだ選ばれていない。選ばずに離れたセットはこのまま残る */
	OPEN,

	/** どれかが選ばれた。選ばれたカードには chosen の印が付く */
	CHOSEN,

	/** 「別の案を見る」が押された。このセットは使われずに終わる */
	RETOPIC
}
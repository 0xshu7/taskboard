package com.example.taskboard.domain;

// ===== インポート =====
// なし。
// この列挙型は Java の標準機能だけで書けるので、外から借りる部品は無い。

/**
 * タスクの状態。未実施 → 進行中 → 完了 の3つ。
 *
 * 決まった3つしか入らないため、String ではなく列挙型にしている。
 * String では値の揺れや打ち間違いが実行時まで分からないが、
 * 列挙型なら記述した時点で誤りが分かる。
 *
 * 状態を進める処理は TaskService.nextStatus にあり、
 * TODO → DOING → DONE → TODO と一周する。
 *
 * 画面での使われ方は2通り。
 * 1. 文字として … th:switch で「未実施」「進行中」に置き換える
 * 2. 色として  … 'tag-' + ${task.status} で tag-TODO などのCSSクラス名を作る
 *
 * データベースには文字列で保存する（Task の @Enumerated(EnumType.STRING)）。
 * 指定しない場合は 0, 1, 2 という並び順の数字で保存されるため、
 * 項目の追加や順序の変更によって、保存済みデータの意味がずれる。
 */
public enum TaskStatus {

	// ===== 値 =====
	// ここに並べたものが、このアプリで使える状態のすべて。
	// 上から順に 0, 1, 2 という内部の番号を持つが、その番号は使わない。

	/** 未実施。作ったばかりの状態 */
	TODO,

	/** 進行中。3択から選んだタスクは、いきなりここから始まる */
	DOING,

	/** 完了。このとき Task.completedAt に時刻が入る */
	DONE
}
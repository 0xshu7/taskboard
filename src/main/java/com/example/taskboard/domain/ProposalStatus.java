/**
 * 提案1セットの状態。1回のスタートで作られる3案が、いまどうなっているかを表す。
 *
 * 状態が変わるのは ProposalService の中だけで、次の3か所。
 * 1. 3案を作った直後            → OPEN
 * 2. カードが選ばれたとき        → CHOSEN（choose）
 * 3. 別の話題にするが押されたとき → RETOPIC（retopic）
 * 4. 期限を過ぎたセットを見つけたとき → EXPIRED（start の中で古いセットを片づける）
 *
 * OPEN は「まだ使える1セット」という意味を持つ。
 * スタート画面を開いた時点で3案を裏で作っておき（事前生成）、
 * スタートが押されたら OPEN のセットを探して、待たずに表示する。
 *
 * 期限が要るのは、事前生成が使われないまま残ることがあるため。
 * 数時間前に作った3案は、そのときの状況に合っていない。
 * 期限は app.proposal.expire-minutes（既定30分）で設定する。
 *
 * CHOSEN と RETOPIC は実績の集計にも使う。
 * CHOSEN の件数が「3択から選んだ回数」であり、レベルの点の一部になる。
 *
 * データベースには文字列で保存する（ProposalSet の @Enumerated(EnumType.STRING)）。
 */
public enum ProposalStatus {

	// ===== 値 =====

	/** 3案を出して、まだ選ばれていない。この状態のセットだけが再利用できる */
	OPEN,

	/** どれかが選ばれた。選んだ回数として集計される */
	CHOSEN,

	/** 「別の話題にする」が押された。このセットは使われずに終わる */
	RETOPIC,

	/** 時間切れ。作られてから一定時間が過ぎ、使われないまま破棄された */
	EXPIRED
}
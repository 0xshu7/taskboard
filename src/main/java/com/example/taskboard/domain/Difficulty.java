/**
 * 難易度。低・中・高の3段階。
 *
 * タスクと提案カードの両方が持つ。
 * タスクでは手で入力した値、カードでは AI が判断した値が入る。
 * カードから作られたタスクは、カードの難易度をそのまま引き継ぐ。
 *
 * 画面での使われ方は2通り。
 * 1. 文字として … ${task.difficulty.label} で「低」「中」「高」と出す
 * 2. 色として  … 'badge-' + ${task.difficulty} で badge-LOW などのCSSクラス名を作る
 *
 * 2つ目は名前のほうを使っている。
 * ラベルではなく LOW / MID / HIGH が入るので、
 * 日本語のラベルを変えても、色の指定は影響を受けない。
 *
 * それぞれに label（画面に出す日本語）を持たせている。
 * 表示の文言をコード側にまとめておくと、画面側で条件分岐を書かずに済み、
 * 文言を直すときも1か所で済む。
 *
 * データベースには文字列で保存する（@Enumerated(EnumType.STRING)）。
 * 指定しない場合は 0, 1, 2 という並び順の数字で保存されるため、
 * 項目の追加や順序の変更によって、保存済みデータの意味がずれる。
 */
public enum Difficulty {

	// ===== 値 =====
	// 括弧の中は、下のコンストラクタに渡す label。

	/** 低。手が出しやすい */
	LOW("低"),

	/** 中。タスクを手で追加したときの初期値 */
	MID("中"),

	/** 高。重いもの */
	HIGH("高");

	// ===== フィールド =====

	/**
	 * 画面に出す日本語。
	 *
	 * final なので、いちど入れたら変えられない。
	 * 列挙型の値はアプリ全体で1つずつしか存在しないため、
	 * 書き換えられるとどこから見ても変わってしまう。それを防いでいる。
	 */
	private final String label;

	// ===== コンストラクタ =====

	/**
	 * 上に並べた値から呼ばれる。
	 *
	 * 列挙型のコンストラクタは必ず private 扱いになるため、
	 * private を書いても書かなくても同じ意味になる。
	 * 外から new Difficulty(...) と書くことはできない。
	 */
	private Difficulty(String label) {
		this.label = label;
	}

	// ===== メソッド =====

	/**
	 * 画面に出す日本語を返す。
	 *
	 * 画面からは ${task.difficulty.label} の形で呼ばれる。
	 * Thymeleaf は .label と書かれたとき getLabel() を探しに行くので、
	 * この getter が無いと値を読めない。
	 */
	public String getLabel() {
		return label;
	}
}
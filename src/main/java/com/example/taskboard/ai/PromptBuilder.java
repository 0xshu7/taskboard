package com.example.taskboard.ai;

// ===== インポート =====
// java.util.List … リストの型。かかえているタスクを受け取るのに使う
//
// 以下は Spring の部品。
// Component … Spring に管理させるクラスです、という印
//
// 以下はこのアプリの部品。
// Task      … タスク1件
// Situation … いまの状況（時間帯と方針）

import java.util.List;

import org.springframework.stereotype.Component;

import com.example.taskboard.domain.Task;
import com.example.taskboard.logic.Situation;

/**
 * AI に送る文章を組み立てる。
 *
 * このアプリで一番大事なファイル。
 * 同じ AI を使っても、ここに何を書くかで返ってくる3案がまるで変わる。
 * コードの正しさではなく、書いてある日本語の質が結果を決める。
 *
 * 組み立てる順番には意味がある。
 *
 * 1. 誰に向けて話すか（この人について）
 * 2. いまの状況
 * 3. 材料（かかえていること）
 * 4. 何を作るかの定義
 * 5. 3案の重さ
 * 6. 守ること
 * 7. 出力の形
 *
 * 定義を重さより先に置いているのは、
 * 「タスクとは何か」が決まっていないと、重さを指定しても意味がないため。
 *
 * 版（VERSION）を先頭に書き込んでいる。
 * この文章はそのまま proposal_sets.prompt_text に保存されるので、
 * あとから「どの版が、どんな3案を出したか」を突き合わせられる。
 *
 * 【これまでに分かったこと】
 *
 * 守りやすいルールが、守りにくいルールを押しのける。
 * 「終わりが目で見える状態を書け」は具体的で守りやすく、
 * それを一番簡単に満たせるのは物理的な小さい作業になる。
 * 指示を守ろうとするほど、判定しやすいほうへ逃げる。
 *
 * 曖昧な指定は効かない。
 * 「重さを散らせ」と書いても散らなかったが、
 * 「3〜10分」「20〜60分」と数字で区切ると効いた。
 *
 * 材料が偏ると提案も偏る。
 * AI が知っているのはタスク一覧だけなので、そこに無いものは出せない。
 * 偏ったまま選び続けると、その話題のタスクがさらに増え、偏りが強まる。
 * これは AI の問題ではなく、入力の問題になる。
 */
@Component
public class PromptBuilder {

	// ===== フィールド =====

	/**
	 * プロンプトの版。
	 *
	 * 文章の先頭に書き込み、proposal_sets.prompt_text に一緒に保存される。
	 * 版ごとの出力を比べられるようにするための目印。
	 *
	 * 文章を直したら、必ずここも上げる。
	 * 上げ忘れると、違う文章が同じ版として記録される。
	 */
	private static final String VERSION = "v1.6";

	/**
	 * 本人の情報。
	 *
	 * 初回ヒアリング（F-02）を作るまでの仮置きで、いまは固定の文章になっている。
	 * 本来はデータベースから、その人について書かれたものを読む。
	 *
	 * ここが固定であることが、いまの提案の質を抑えている。
	 * AI はこの4行とタスク一覧しか知らないので、
	 * それ以外の話題は出しようがない。
	 *
	 * """ で囲む書き方はテキストブロックという。
	 * 改行をそのまま書けるので、複数行の文章を読みやすく書ける。
	 * 使わない場合は "・専門学校生。\n・自炊を…" のように \n をつなぐことになる。
	 */
	private static final String PROFILE = """
			・専門学校生。資格の勉強をしている
			・自炊をしたいが、面倒で後回しにしがち
			・休日は何もしないまま終わることが多い
			・やり始めれば集中できるが、始めるまでが長い
			""";

	// ===== メソッド =====

	/**
	 * 3案を出してもらうための文章を組み立てる。
	 *
	 * @param situation   いまの状況。SituationJudge が時刻から判断したもの
	 * @param activeTasks いま未完了のタスク。提案の材料になる
	 * @param pickedTask  3つ目にそのまま使うタスク。1件も無ければ null
	 * @return AI に送る文章
	 */
	public String buildProposal(Situation situation, List<Task> activeTasks, Task pickedTask) {

		StringBuilder p = new StringBuilder();

		// --- 版と、話し手の立場 ---
		// 「指示も励ましもしません」を最初に置く。
		// 何をしないかを先に決めておくと、全体の調子がそろう。

		p.append("# prompt ").append(VERSION).append("\n\n");

		p.append("あなたは、動き出せない人のそばにいる人です。指示も励ましもしません。\n\n");

		// --- 誰に向けて話すか ---

		p.append("【この人について】\n");
		p.append(PROFILE).append("\n");

		// --- いまの状況 ---
		// 時間帯はアプリ側で判断している（SituationJudge）。
		// 誰にとっても同じことはこちらで決め、人によって違うことだけ AI に渡す。

		p.append("【今の状況】\n");
		p.append("時間帯：").append(situation.getTimeOfDay()).append("\n");
		p.append("方針：").append(situation.getNote()).append("\n\n");

		// --- 材料 ---
		// ここが提案の元になる。空のときの書き方も決めておく。
		// 何も書かないと、AI が勝手に想像で埋めてしまう。

		p.append("【今かかえていること】\n");
		if (activeTasks.isEmpty()) {
			p.append("（登録されているものはありません）\n");
		} else {
			for (Task task : activeTasks) {
				p.append("・").append(task.getTitle());
				if (task.getDueDate() != null) {
					p.append("（締切 ").append(task.getDueDate()).append("）");
				}
				p.append("\n");
			}
		}
		p.append("\n");

		// --- 何を作るかの定義 ---
		// v1.3 の中心。3つの条件を全部満たすものだけをタスクと呼ぶ。
		//
		// 1つ目が完璧主義の人のため。終わりが文に書いてあれば、
		// 本人がどう思っていても終われる。採点する役目が本人の外に出る。
		//
		// 2つ目が動き出せない人のため。始める前に判断が挟まると、そこで止まる。
		//
		// 3つ目が「動くこと」と「タスク管理」をつなぐ条件。
		// これが無いと、散歩や深呼吸のような、やっても何も進まないものが出る。

		p.append("【このアプリでの「タスク」の定義】\n");
		p.append("次の3つを全部満たすものだけを、タスクと呼びます。\n");
		p.append("1. 書いてあることだけをやれば「終わった」と言い切れる。\n");
		p.append("　 どこまでやれば終わりかが、文に書いてある。\n");
		p.append("2. 今いる場所で、何も決めず、何も探さずに始められる。\n");
		p.append("3. やると、この人がかかえていることが目に見えて前に進む。\n\n");

		// --- 3つの案 ---
		// 3つ目は、リストにあるタスクをそのまま使う。
		//
		// 押すたびに新しいタスクが増え続けるのを防ぎ、
		// 登録したまま止まっているものを掘り起こすため。
		// 止まっているタスクは、たいてい何をすればいいか決まっていないもので、
		// ヒントが付けば動き出せる。
		//
		// どれを拾うかはアプリ側でランダムに選んでいる。
		// AI に選ばせると、選ぶ基準を書くことになって指示が増える。
		//
		// 「散らせ」という書き方では効かなかった。
		// 1分・15分・3分が返ってきて、AI から見れば散っている扱いだった。
		// 数字で範囲を区切ると効くようになった。

		p.append("【3つの案】\n");
		p.append("estimatedMinutes は、次の範囲を必ず守ってください。\n");
		p.append("1つ目：3〜10分。今日はもう動けないと思っている人でも手が出るもの。\n");
		p.append("2つ目：20〜60分。20分未満は禁止です。今日中に終わって、進んだと目で分かるもの。\n");

		if (pickedTask != null) {
			p.append("3つ目：下に指定するタスクです。title は一字も変えずにそのまま使い、\n");
			p.append("　　　　detail（完了のヒント）だけを書いてください。\n");
			p.append("　　　　estimatedMinutes と difficulty は、その内容から見積もってください。\n\n");

			p.append("【3つ目に使うタスク】\n");
			p.append(pickedTask.getTitle()).append("\n\n");
		} else {
			p.append("3つ目：分数は問わない。ただし「作業」ではなく、\n");
			p.append("　　　　手が止まっている原因そのものを片づけるもの（決める・確かめる・聞く のどれか）。\n\n");
		}

		// --- 時間帯ごとの言い回し ---
		// 時間帯を「朝」とだけ渡しても、AI はいつでも成立する無難な案を返す。
		// その時間が「何をする時間か」と、実際に使う言葉の両方を渡す。
		//
		// title は短い名札でよい。中身は detail が持っている。
		// 「ペンを1本出す」と「朝の爆速スイッチ」では、同じ内容でも手の伸び方が違う。

		p.append("【title の付け方】\n");
		p.append("title は一文にしてください。中黒（・）や記号で言葉をつなげてはいけません。\n");
		p.append("「〇〇として、△△する」の形にします。\n");
		p.append("〇〇は下から選んだ時間帯の言葉、△△はその案で実際にやることです。\n");
		p.append("例：午後いちばんの一歩として、5分だけ参考書を読む\n");
		p.append("　　朝の集中力アップとして、机の上のものを3つ戻す\n\n");

		p.append("朝（立ち上げ・スイッチオン）\n");
		p.append("　朝の集中力アップ／出かける前にサクッと／朝活スタート／\n");
		p.append("　朝の爆速スイッチ／気持ちよく1日を始める／朝のロケットスタート\n");

		p.append("昼（仕切り直し・リフレッシュ）\n");
		p.append("　午後いちばんの一歩／午後のリフレッシュ／昼活スタート／\n");
		p.append("　午後バテ防止の／ここからギア上げ／午後の自分にパス\n");

		p.append("夜（アクティブ・集中・自分の時間）\n");
		p.append("　夜活スタート／ここから一発集中／夜のギア上げ／\n");
		p.append("　自分時間スタート／ガッツリ夜集中／今夜のメインイベント\n");

		p.append("深夜（レビュー・労い・ログ）\n");
		p.append("　明日の自分をラクにする／夜のreview／今日のごほうび／\n");
		p.append("　おつかれさまを自分に／脳内デトックス／今日のおしまいログ\n\n");

		p.append("上の言葉をそのまま使っても、少し変えても構いません。\n");
		p.append("3案それぞれ、違う言葉を使ってください。同じ頭が2つ並ぶと選びにくくなります。\n");
		p.append("いつ見ても同じに読める title は失敗です。\n");
		p.append("ただし、指定されたタスクを使う案には当てはめません。title はそのままにしてください。\n\n");

		// --- 粒度の基準 ---
		// 基準を書かないと、3分の案に GROUP が付くようなことが起きる。

		p.append("【granularity の決め方】\n");
		p.append("FIVE_MIN＝10分以内 ／ TODAY＝今日中に終わる ／ GROUP＝複数回に分かれる\n");
		p.append("estimatedMinutes と食い違わせないでください。\n\n");

		// --- 守ること ---
		// 禁止を並べる欄。
		// ゴミ捨てのような小さな作業は禁止していない。
		// 動くこと自体が目的なので、小ささは問題にならない。

		p.append("【守ること】\n");
		p.append("・かかえていることを、そのままの言葉で返さない。必ず切り出して、小さくして返す。\n");
		p.append("・「がんばる」「整理する」「見直す」「向き合う」など、終わりの無い言葉を使わない。\n");
		p.append("・買いに行く・どこかへ移動する・誰かの返事を待つ、が必要なものは出さない。\n");
		p.append("・観測した行動（迷った時間、できなかった日数など）を文面で指摘しない。\n");
		p.append("・説教しない。急かさない。がんばれと言わない。\n\n");

		// --- title と detail の役割分担 ---
		// title は選ぶときに見るもの、detail は選んだあとに手を動かすためのもの。
		// 一致させる必要はない、と明記しておかないと要約が返ってくる。

		p.append("【title と detail の関係】\n");
		p.append("title は、選ぶときに見るものです。detail の要約である必要はありません。\n");
		p.append("その案が何なのかが一目で分かる短い言葉にしてください。\n");
		p.append("detail は、選んだあとに手を動かすためのものなので、title より具体的で構いません。\n\n");

		// --- detail の書き方 ---
		// 最後の1行を「終わり：」で始めさせるのが、この設計の中心。
		//
		// \\n と2つ書いているのは、Java の文字列の中で
		// 「\n という2文字」を送りたいため。
		// \n と1つだけ書くと、そこで改行してしまい、AI には伝わらない。

		p.append("【detail の書き方】\n");
		p.append("動作を2〜3行書いたあと、最後の1行を必ず「終わり：」で始めてください。\n");
		p.append("・動作の行は、1行に1つの動作だけ。「〜する」で終える。\n");
		p.append("・最後の行は「終わり：」に続けて、やり終えたときに目で見える状態を書く。\n");
		p.append("・その状態になったら、本人がどう思っていても終わりです。そう書けるものだけを書く。\n");
		p.append("・行の区切りは改行（\\n）にする。\n");
		p.append("・行の区切りは改行（\\n）にする。\n");
		p.append("・全体で250字を超えないようにする。保存できる上限が決まっているため。\n");
		p.append("例：\n");
		p.append("　　机の上のものを全部いったん床に置く\n");
		p.append("　　書類だけを拾って1か所に積む\n");
		p.append("　　明らかなゴミだけ捨てる\n");
		p.append("　　終わり：机の上に書類の山が1つだけある\n\n");

		// --- 出力の形 ---
		// 実際の型の固定は responseSchema で行っているが、
		// ここにも書いておく。文章と設定の両方でそろえたほうが、崩れにくい。

		p.append("【出力】\n");
		p.append("cards という配列に3件。1つ目・2つ目・3つ目は上の重さの順に並べる。\n");
		p.append("各件は次の項目を持つ。\n");
		p.append("title（30字以内）／category（生活・勉強・食事・休日 のいずれか）／\n");
		p.append("granularity（FIVE_MIN・TODAY・GROUP）／difficulty（LOW・MID・HIGH）／\n");
		p.append("estimatedMinutes（整数）／reason（40字以内）／detail（上の書き方）\n");
		
		return p.toString();
	}
}